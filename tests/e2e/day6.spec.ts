import { test, expect, type Page } from '@playwright/test';
import { PDFDocument, StandardFonts } from 'pdf-lib';
import { authResponseSchema, draftBatchSchema, riskListSchema, documentListSchema, type AssistantResult } from '@supplypilot/contracts';
async function login(page: Page, role: 'STAFF' | 'MANAGER') {
  const email = process.env[`SEED_${role}_EMAIL`]; const password = process.env[`SEED_${role}_PASSWORD`];
  if (!email || !password) throw new Error('Missing isolated test credentials.');
  await page.goto('/login'); await page.getByLabel('Email', { exact: true }).fill(email); await page.getByLabel('Password', { exact: true }).fill(password); await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible();
}
test('mocked assistant transport recovers a lost response with the same key and links a real draft for manager review', async ({ page }) => {
  await login(page, 'MANAGER');
  const identity = authResponseSchema.parse(await (await page.request.get('/api/auth/me')).json());
  const inventory = riskListSchema.parse(await (await page.request.get('/api/inventory/risks?search=SP-003')).json());
  const product = inventory.items[0]; if (!product) throw new Error('Missing fixture product');
  const runId = crypto.randomUUID(); let originalKey: string | undefined; let originalBody: unknown; let proposalId = ''; let calls = 0;
  await page.route('**/api/assistant/runs', async (route) => {
    calls++;
    const key = route.request().headers()['idempotency-key']; const body: unknown = route.request().postDataJSON();
    if (calls === 1) {
      originalKey = key; originalBody = body;
      const response = await page.request.post('/api/proposals', { headers: { origin: 'http://localhost:5183', 'x-csrf-token': identity.csrfToken, 'idempotency-key': `ui-${key}` }, data: { items: [{ productId: product.productId, quantity: 2 }], reason: 'Day 6 browser fixture; mocked model transport' } });
      expect(response.ok()).toBe(true);
      const batch = draftBatchSchema.parse(await response.json()); proposalId = batch.proposals[0]?.id ?? ''; expect(proposalId).not.toBe('');
      await route.abort('connectionreset'); return;
    }
    expect(key).toBe(originalKey); expect(body).toEqual(originalBody);
    const result: AssistantResult = { runId, status: 'COMPLETED', intent: 'DRAFT_REQUEST', answer: 'Draft saved for manager review.', data: [], knowledge: [], warnings: [], createdProposalIds: [proposalId], toolCalls: 6, errorCode: null };
    await route.fulfill({ json: result });
  });
  await page.getByLabel('Ask the assistant').fill('Create a draft for the selected product');
  await page.getByLabel('Search inventory').fill('SP-003');
  await page.getByLabel('Select inventory SP-003', { exact: true }).check();
  await page.getByLabel('Assistant quantity for SP-003').fill('2');
  await page.getByLabel('Allow draft proposals').check();
  await page.getByRole('button', { name: 'Send question' }).click();
  await expect(page.getByRole('button', { name: 'Recover saved request' })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Recover saved request' }).click();
  await page.getByRole('link', { name: 'Open draft proposal 1' }).click();
  await expect(page).toHaveURL(new RegExp(`/proposals/${proposalId}$`));
  await expect(page.getByRole('heading', { name: 'Products in this proposal' })).toBeVisible();
  await expect(page.getByText('DRAFT', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Approve', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm approval' }).click();
  await expect(page.getByText('APPROVED', { exact: true })).toBeVisible();
  expect(calls).toBe(2);
});
test('real PDF upload, local retrieval, citation revalidation and contract isolation work through the browser', async ({ page, browser }) => {
  await login(page, 'MANAGER'); await page.getByRole('link', { name: 'Knowledge', exact: true }).click();
  const pdf = await PDFDocument.create(); const font = await pdf.embedFont(StandardFonts.Helvetica);
  pdf.addPage().drawText('Procurement policy: Compare supplier price and delivery lead time before purchasing.', { x: 40, y: 700, font, size: 12 });
  const bytes = Buffer.from(await pdf.save());
  await page.getByLabel('Document title').fill('Day 6 synthetic browser policy');
  await page.getByLabel('PDF file').setInputFiles({ name: 'day6-policy.pdf', mimeType: 'application/pdf', buffer: bytes });
  await page.getByRole('button', { name: 'Upload PDF' }).click();
  await expect(page.getByRole('heading', { name: 'Day 6 synthetic browser policy', exact: true })).toBeVisible();
  await expect(page.getByText('READY', { exact: true })).toBeVisible({ timeout: 30000 });
  await page.getByLabel('Search knowledge').fill('Compare supplier price and delivery lead time before purchasing');
  await page.getByRole('button', { name: 'Search documents' }).click();
  await expect(page.getByText('Supporting evidence found')).toBeVisible();
  await page.getByRole('button', { name: 'View source 1 · page 1' }).click();
  await expect(page.getByRole('link', { name: 'Download source PDF · page 1' })).toBeVisible();
  await page.screenshot({ path: '.cache/day6-knowledge.png', fullPage: true });
  const policyList = documentListSchema.parse(await (await page.request.get('/api/knowledge/documents')).json()); const policy = policyList.items.find((doc) => doc.title === 'Day 6 synthetic browser policy'); if (!policy) throw new Error('Missing uploaded policy');
  await page.getByLabel('Document type').selectOption('SUPPLIER_CONTRACT');
  const supplier = page.getByRole('combobox', { name: 'Supplier', exact: true });
  await expect(supplier.locator('option')).toHaveCount(11);
  const supplierId = await supplier.locator('option').nth(1).getAttribute('value'); if (!supplierId) throw new Error('Missing supplier');
  await supplier.selectOption(supplierId);
  await page.getByLabel('Document title').fill('Private supplier contract fixture');
  await page.getByLabel('PDF file').setInputFiles({ name: 'contract.pdf', mimeType: 'application/pdf', buffer: bytes });
  await page.getByRole('button', { name: 'Upload PDF' }).click();
  await expect(page.getByText('READY', { exact: true })).toBeVisible({ timeout: 30000 });
  const contracts = documentListSchema.parse(await (await page.request.get(`/api/knowledge/documents?type=SUPPLIER_CONTRACT&supplierId=${supplierId}`)).json()); const contract = contracts.items[0]; if (!contract) throw new Error('Missing contract');
  const context = await browser.newContext(); const staff = await context.newPage(); await login(staff, 'STAFF'); await staff.getByRole('link', { name: 'Knowledge', exact: true }).click();
  await expect(staff.getByRole('heading', { name: policy.title, exact: true })).toBeVisible();
  await expect(staff.getByRole('button', { name: 'Upload PDF' })).toHaveCount(0); await expect(staff.getByRole('option', { name: 'Supplier contracts' })).toHaveCount(0);
  expect((await staff.request.get(`/api/knowledge/documents/${contract.id}/file?supplierId=${supplierId}`)).status()).toBe(404);
  expect((await staff.request.get('/api/knowledge/suppliers')).status()).toBe(403);
  await staff.getByLabel('Search knowledge').fill('Compare supplier price and delivery lead time'); await staff.getByRole('button', { name: 'Search documents' }).click();
  await expect(staff.getByText('Supporting evidence found')).toBeVisible();
  await page.getByLabel('Document type').selectOption('PROCUREMENT_POLICY'); await page.getByRole('button', { name: 'Archive', exact: true }).click(); await page.getByRole('button', { name: 'Confirm archive' }).click();
  await expect(page.getByText('ARCHIVED', { exact: true })).toBeVisible();
  await staff.getByRole('button', { name: 'View source 1 · page 1' }).click();
  await expect(staff.getByText('Citation is unavailable.')).toBeVisible();
  await expect(staff.getByRole('link', { name: 'Download source PDF · page 1' })).toHaveCount(0);
  await staff.setViewportSize({ width: 390, height: 844 }); await staff.screenshot({ path: '.cache/day6-knowledge-mobile.png', fullPage: true });
  expect(await staff.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await context.close();
});
